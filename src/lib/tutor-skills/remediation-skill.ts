export function buildRemediationPrompt(
  question: string,
  studentAnswer: string,
  attemptCount: number,
  sourceMaterial: string
): string {
  let strategy = '';
  if (attemptCount <= 2) {
    strategy = 'اشرح المفهوم باستخدام زاوية مختلفة أو مثال مختلف تمامًا عن الشرح الأصلي.';
  } else if (attemptCount <= 4) {
    strategy = 'ارجع إلى المفهوم الأساسي أو الأولي المرتبط بالسؤال للتحقق من عدم وجود فجوة في الفهم الأساسي للطالب.';
  } else {
    strategy = 'اكسر الجزئية التي أخطأ فيها الطالب إلى خطوات مصغرة جدًا (Micro-steps). اطرح سؤالًا توجيهيًا بسيطًا جدًا لمساعدته على إدراك الخطأ.';
  }

  return `أنت معلم خبير وصابر، وتعمل على توجيه طالب أخطأ في إجابة سؤال ضمن حلقة إتقان.
هدفك الأهم هو **عدم إعطاء الإجابة الصحيحة بشكل مباشر**. يجب أن توجه الطالب ليصل إليها بنفسه.

السؤال الذي أخطأ فيه: "${question}"
إجابة الطالب الخاطئة: "${studentAnswer}"
رقم المحاولة: ${attemptCount}

الاستراتيجية الإجبارية لهذه المحاولة:
${strategy}

المحتوى التعليمي (للاعتماد عليه في توجيهك):
"""
${sourceMaterial}
"""

قدم ردًا داعمًا، بنّاءً، ويوجه الطالب خطوة بخطوة باللغة العربية. تأكد من تطبيق الاستراتيجية المطلوبة أعلاه.`;
}
