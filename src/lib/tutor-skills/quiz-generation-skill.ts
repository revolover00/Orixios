export function buildQuizGenerationPrompt(
  sourceMaterial: string,
  numQuestions: number,
  quizType: string
): string {
  return `أنت معلم خبير متخصص في اختبار وتقييم الطلاب.
المطلوب منك توليد اختبار (Quiz) من نوع "${quizType}" يحتوي على ${numQuestions} أسئلة اختيار من متعدد.
يجب أن تعتمد حصريًا على المحتوى التعليمي التالي. لا تضف أي معلومات خارجية ولا تخترع حقائق غير موجودة في هذا النص.

المحتوى التعليمي (المصدر الموثوق):
"""
${sourceMaterial}
"""

قواعد الأسئلة:
1. يجب أن يكون لكل سؤال 4 خيارات منطقية ومكتوبة بعناية.
2. يجب أن يكون هناك إجابة صحيحة واحدة فقط من بين الخيارات.
3. يجب أن تتطابق الإجابة الصحيحة تمامًا مع أحد الخيارات.
4. أضف شرحًا موجزًا يوضح سبب صحة الإجابة استنادًا للمصدر.

يجب أن يكون ناتجك حصريًا بصيغة JSON صالحة (Valid JSON) وفقًا للهيكل التالي، بدون أي نصوص إضافية أو علامات Markdown خارج الـ JSON:
{
  "questions": [
    {
      "id": "معرف_فريد_من_اختيارك",
      "text": "نص السؤال هنا",
      "options": ["خيار 1", "خيار 2", "خيار 3", "خيار 4"],
      "correctAnswer": "الخيار الصحيح هنا بالضبط",
      "explanation": "شرح الإجابة"
    }
  ]
}`;
}
